type LevelExamples = readonly [string, string, string, string, string];

function createTrack(
  id: string,
  name: string,
  description: string,
  examples: LevelExamples,
): Track {
  return {
    id,
    name,
    description,
    levels: LEVELS.map((level, levelIndex) => ({
      ...level,
      examples: [examples[levelIndex]!],
    })),
  };
}

